param(
    [string]$MakeNSIS,
    [string]$PackageCache = (Join-Path $env:USERPROFILE '.nuget\packages'),
    [switch]$Offline
)
$ErrorActionPreference = 'Stop'
$repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$project = Join-Path $repo 'wealth-tracker\wealth-tracker.csproj'
$output = Join-Path $repo 'artifacts\installer'
$publish = Join-Path $output 'publish'
$dist = Join-Path $output 'dist'
$setup = Join-Path $dist 'WealthTracker-1.0.0-win-x64-setup.exe'
# Prevent stale or personal files from entering a later package.
$root = $repo.TrimEnd('\') + '\artifacts\installer\'
if (![IO.Path]::GetFullPath($publish).StartsWith($root, [StringComparison]::OrdinalIgnoreCase)) { throw 'Unsafe publish directory.' }
if (Test-Path -LiteralPath $publish) { Remove-Item -LiteralPath $publish -Recurse -Force }
New-Item -ItemType Directory -Force -Path $publish, $dist | Out-Null
$restore = @("-p:RestorePackagesPath=$PackageCache", '-p:NuGetAudit=false')
if ($Offline) { $restore += @('--configfile', (Join-Path $PSScriptRoot 'NuGet.offline.config')) }
& dotnet publish $project @restore -c Release -r win-x64 --self-contained true -p:RuntimeFrameworkVersion=8.0.21 -p:PublishSingleFile=false -p:DebugType=None -p:DebugSymbols=false -o $publish
if ($LASTEXITCODE -ne 0) { throw 'Application publication failed.' }
foreach ($required in @('wealth-tracker.exe', 'docs\index.html')) {
    if (!(Test-Path -LiteralPath (Join-Path $publish $required))) { throw "Missing published file: $required" }
}
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'INSTALLATION.txt') -Destination $publish -Force
$files = @(Get-ChildItem -LiteralPath $publish -Recurse -File | Sort-Object FullName)
if ($files | Where-Object { $_.Extension -in @('.db', '.sqlite', '.sqlite3') -or $_.Name -match '\.db-(wal|shm)$' }) { throw 'A database was found in the package. Remove personal data from publication.' }
$delete = @('; Generated by build-installer.ps1. Delete known package files only.')
$checksums = @()
foreach ($file in $files) {
    $relative = $file.FullName.Substring($publish.Length + 1)
    if ($relative.Contains('$') -or $relative.Contains('"')) { throw "Unsupported package filename: $relative" }
    $delete += 'Delete "$INSTDIR\' + $relative + '"'
    $checksums += '{0}  {1}' -f (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash, $relative
}
foreach ($directory in (Get-ChildItem -LiteralPath $publish -Recurse -Directory | Sort-Object { $_.FullName.Length } -Descending)) {
    $delete += 'RMDir "$INSTDIR\' + $directory.FullName.Substring($publish.Length + 1) + '"'
}
$manifest = Join-Path $output 'uninstall-files.nsh'
$delete | Set-Content -LiteralPath $manifest -Encoding utf8
$checksums | Set-Content -LiteralPath (Join-Path $dist 'payload-sha256.txt') -Encoding utf8
if (!$MakeNSIS) {
    $command = Get-Command makensis.exe -ErrorAction SilentlyContinue
    if ($command) { $MakeNSIS = $command.Source }
    foreach ($candidate in @('C:\Program Files (x86)\NSIS\makensis.exe', 'C:\Program Files\NSIS\makensis.exe')) {
        if (!$MakeNSIS -and (Test-Path -LiteralPath $candidate)) { $MakeNSIS = $candidate }
    }
}
if (!$MakeNSIS -or !(Test-Path -LiteralPath $MakeNSIS)) { throw 'NSIS 3.x is required. Supply -MakeNSIS path\makensis.exe.' }
& $MakeNSIS /INPUTCHARSET UTF8 "/DPUBLISH_DIR=$publish" "/DOUTPUT_FILE=$setup" "/DUNINSTALL_INCLUDE=$manifest" (Join-Path $PSScriptRoot 'WealthTracker.nsi')
if ($LASTEXITCODE -ne 0) { throw 'Installer compilation failed.' }
$hash = Get-FileHash -LiteralPath $setup -Algorithm SHA256
"$($hash.Hash)  $([IO.Path]::GetFileName($setup))" | Set-Content -LiteralPath (Join-Path $dist 'setup-sha256.txt') -Encoding utf8
Write-Host "Installer: $setup"
$hash | Format-List
